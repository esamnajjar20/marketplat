import { readFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const mobileDir = resolve(fileURLToPath(new URL('..', import.meta.url)));
const repoRoot = resolve(mobileDir, '../..');
const read = (path) => readFileSync(join(repoRoot, path), 'utf8');
const checks = [];
const check = (label, condition) => { assert.ok(condition, label); checks.push(label); };
const schema = read('apps/api/prisma/schema.prisma');
const routes = read('apps/api/src/routes.ts');
const service = read('apps/api/src/modules/marketplace-orders/marketplace-orders.service.ts');
const api = read('apps/mobile/src/features/commerce/orders.api.ts');
const detail = read('apps/mobile/app/products/[id].tsx');
const checkout = read('apps/mobile/app/order-checkout.tsx');
const orderDetail = read('apps/mobile/app/orders/[id].tsx');
check('Prisma schema defines independent marketplace order models', /model MarketplaceOrder \{/.test(schema) && /model MarketplaceOrderItem \{/.test(schema));
check('Buyer and seller order relations exist', /ordersAsBuyer\s+MarketplaceOrder\[\].*OrdersAsBuyer/.test(schema) && /ordersAsSeller\s+MarketplaceOrder\[\].*OrdersAsSeller/.test(schema));
check('API mounts authenticated marketplace orders router', /router\.use\('\/orders', marketplaceOrdersRouter\)/.test(routes));
check('Checkout validates product availability and stock on server', /stockQuantity: \{ gte: item\.quantity \}/.test(service) && /PRODUCT_UNAVAILABLE/.test(service));
check('Order totals are calculated from database product prices', /const total = roundMoney\(subtotal \+ shippingFee\)/.test(service) && /unitPrice = roundMoney\(unitPrice\)/.test(service));
check('Order creation has idempotency protection', /findByIdempotencyKey/.test(service) && /idempotencyKey/.test(api));
check('Stock changes are recorded and cancellation restores inventory', /tx\.stockMovement\.create/.test(service) && /Marketplace order .* cancellation/.test(service));
check('API exposes buyer and seller order flows', /\/api\/v1\/orders\/mine/.test(api) && /\/api\/v1\/orders\/seller/.test(api));
check('Product detail can launch checkout', /order-checkout/.test(detail));
check('Checkout provides delivery details and cash-on-delivery', /recipientPhone/.test(checkout) && /الدفع عند الاستلام/.test(checkout));
check('Order detail exposes controlled status actions', /updateMarketplaceOrderStatus/.test(orderDetail) && /nextStatus/.test(orderDetail));
check('Migration file exists', existsSync(join(repoRoot, 'apps/api/prisma/migrations/20261026120000_add_marketplace_orders/migration.sql')));
console.log(`Feature orders verification passed (${checks.length} checks).`);
for (const label of checks) console.log(`✓ ${label}`);
