import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';

const queue = readFileSync(new URL('../src/storage/chat-message-outbox.ts', import.meta.url), 'utf8');
const sync = readFileSync(new URL('../src/features/messaging/chat-message-outbox-sync.ts', import.meta.url), 'utf8');
const bridge = readFileSync(new URL('../src/storage/ChatMessageOutboxLifecycleBridge.tsx', import.meta.url), 'utf8');
const screen = readFileSync(new URL('../app/messages/[id].tsx', import.meta.url), 'utf8');
const layout = readFileSync(new URL('../app/_layout.tsx', import.meta.url), 'utf8');
const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
assert.match(queue, /CREATE TABLE IF NOT EXISTS chat_message_outbox/, 'SQLite must hold queued text messages across restarts');
assert.match(queue, /owner_id TEXT NOT NULL/, 'queued messages must be scoped to their account');
assert.match(queue, /operation_id TEXT NOT NULL UNIQUE/, 'idempotency IDs must be unique');
assert.match(queue, /withExclusiveTransactionAsync/, 'queue capacity and insert must be atomic');
assert.match(queue, /MAX_PENDING = 50/, 'queue must be bounded');
assert.match(queue, /next_attempt_at = \? \+ MIN\(/, 'failed messages must receive bounded backoff');
assert.match(sync, /listDueChatMessages\(ownerId\)/, 'sync must only process due rows for the current account');
assert.match(sync, /acknowledgeChatMessage\(item\.operationId, ownerId\)/, 'a message is removed only after server success');
assert.match(sync, /listeners\.add\(listener\)/, 'open screens must be notified after queued message delivery');
assert.match(bridge, /NetInfo\.addEventListener/, 'sync must respond to connectivity changes');
assert.match(bridge, /state === 'active'/, 'sync must resume when the app returns to foreground');
assert.match(screen, /listChatMessagesForConversation\(user\.id, id\)/, 'pending local messages must survive screen/app restarts');
assert.match(screen, /حُفظت الرسالة على هذا الجهاز/, 'offline UX must clearly describe local queued status');
assert.match(screen, /if \(!persisted\)/, 'only a message that failed local persistence may be removed from the optimistic UI');
assert.match(layout, /<ChatMessageOutboxLifecycleBridge \/>/, 'chat outbox lifecycle bridge must be mounted at the app root');
assert.match(pkg.scripts.test, /verify-chat-persistent-outbox-audit\.mjs/, 'persistent outbox audit must run in npm test');
console.log('Chat persistent outbox audit checks passed (SQLite persistence, account isolation, retry/backoff, and reconnect lifecycle).');
