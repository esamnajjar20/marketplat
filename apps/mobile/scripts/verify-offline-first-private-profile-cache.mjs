import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const client = readFileSync(resolve(root, 'src/api/client.ts'), 'utf8');
const api = readFileSync(resolve(root, 'src/features/account/account.api.ts'), 'utf8');
const profile = readFileSync(resolve(root, 'app/profile.tsx'), 'utf8');
const settings = readFileSync(resolve(root, 'app/settings.tsx'), 'utf8');
const cache = readFileSync(resolve(root, 'src/storage/public-cache.ts'), 'utf8');
assert.match(client, /privateGetCacheKey/);
assert.match(client, /method\.toUpperCase\(\) !== 'GET' \|\| !token\?\.trim\(\)/);
assert.match(client, /api-private:\$\{encodeURIComponent\(ownerId\)\}/);
assert.match(client, /pathname = path\.split\('\?', 1\)\[0\]/);
assert.ok(client.includes('users' + String.fromCharCode(92) + '/me'));
assert.match(client, /cacheOwnerId/);
assert.match(client, /deletePublicCacheEntry/);
assert.match(api, /fetchMyProfile\(token:string, ownerId\?/);
assert.match(api, /cacheOwnerId:ownerId/);
assert.match(profile, /fetchMyProfile\(accessToken,user\?\.id\)/);
assert.match(profile, /updateMyProfile\([\s\S]*?user\?\.id\)/);
assert.match(settings, /fetchMyProfile\(accessToken, user\?\.id\)/);
assert.match(settings, /updateNotificationPreferences\(prefs, accessToken, csrfToken, user\?\.id\)/);
assert.match(cache, /DELETE FROM public_cache WHERE cache_key = \?/);
console.log('Offline-first private profile cache audit checks passed (static checks only).');
