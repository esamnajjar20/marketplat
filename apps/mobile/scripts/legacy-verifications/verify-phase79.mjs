import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const app = JSON.parse(read('app.json')).expo;
const encryptedDb = read('src/storage/encrypted-database.ts');
const auth = read('src/features/auth/AuthContext.tsx');
const cache = read('src/storage/public-cache.ts');
const media = read('src/storage/chat-media-outbox.ts');
const stream = read('src/features/messaging/chat-live-stream.ts');
const layout = read('app/_layout.tsx');
const backup = read('android/app/src/main/res/xml/secure_store_backup_rules.xml');
const workflow = fs.readFileSync(path.resolve(root, '../../.github/workflows/build-mobile-apk.yml'), 'utf8');

assert.ok(app.plugins.some((plugin) => Array.isArray(plugin) && plugin[0] === 'expo-sqlite' && plugin[1]?.useSQLCipher === true), 'SQLCipher must be enabled in Expo native config');
assert.equal(app.android?.supportsRTL, true, 'Android app config must support RTL');
assert.match(encryptedDb, /PRAGMA cipher_version/, 'Fail closed when SQLCipher is unavailable');
assert.match(encryptedDb, /function serializeTransaction/, 'Serialize transactions across feature stores sharing one SQLite connection');
assert.match(encryptedDb, /transactionQueue\.then\(work, work\)/, 'Transaction queue must recover after a prior transaction rejects');
assert.match(encryptedDb, /if \(Platform\.OS === 'web'\)[\s\S]*throw new Error/, 'Do not silently store private data in plaintext on web');
assert.match(encryptedDb, /PRAGMA key/, 'Set the per-installation database key');
assert.match(encryptedDb, /sqlcipher_export\('encrypted'\)/, 'Legacy database migration must export to encrypted DB');
assert.match(encryptedDb, /deleteDatabaseAsync\(LEGACY_DATABASE_NAME\)/, 'Legacy plaintext DB may only be deleted after verified encrypted open');
assert.match(auth, /countPendingPrivateMobileOperations/, 'Logout must count queued operations');
assert.match(auth, /حذف العمليات والخروج/, 'Logout must explicitly warn before discarding queued writes');
assert.match(auth, /PRIVATE_CLEANUP_REQUIRED_KEY/, 'Failed logout cleanup must block next login/restore');
assert.match(cache, /withExclusiveTransactionAsync/, 'Private data cleanup must be atomic');
assert.match(cache, /export async function countPendingPrivateMobileOperations/, 'Expose queued-operation count');
assert.match(media, /cleanupStaleChatMediaFiles/, 'Implement chat-media retention sweep');
assert.match(media, /ORPHAN_MEDIA_MIN_AGE_MS = 24 \* 60 \* 60 \* 1_000/, 'Use a conservative minimum orphan age');
assert.match(stream, /MAX_SSE_BUFFER_BYTES = 1_000_000/, 'Bound SSE frame buffering by UTF-8 bytes');
assert.match(stream, /MAX_SSE_FRAME_BYTES = 256_000/, 'Reject oversized individual SSE frames');
assert.match(stream, /MAX_SSE_CHUNK_BYTES = 512_000/, 'Reject oversized network chunks before decoding');
assert.match(layout, /I18nManager\.allowRTL\(true\)/, 'Allow RTL without force-flipping existing layouts');
const chatScreen = read('app/messages/[id].tsx');
assert.match(chatScreen, /requestAnimationFrame\(\(\) => requestAnimationFrame\(/, 'Initial chat scrolling waits for committed layout measurements');
assert.match(chatScreen, /initialScrollDone\.current \|\| loadingOlder \|\| userScrolledAway\.current/, 'Initial chat scroll must not override history loading or user position');
assert.match(backup, /marketplat-private-v2\.db/, 'Exclude encrypted private DB from backup rules');
assert.match(workflow, /expo prebuild --platform android --no-install/, 'CI must apply SQLCipher native config before Gradle builds');
console.log('PASS: Phase 79 security hardening static checks.');
console.log('NOT CHECKED: native SQLCipher build/migration, Sentry/native crash reporting, real-device RTL/SSE, concurrent SQLite transactions.');
