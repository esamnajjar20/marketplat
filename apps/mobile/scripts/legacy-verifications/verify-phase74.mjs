assert.match(queue, /writeFavoriteAdIds\(\[\.\.\.merged\], user\.id\)/, 'reconciled cache is persisted');
assert.match(queue, /discardFavoriteState\(user\.id, item\.adId, item\.operationId\)/, 'cancel remains protected against replacing operations');
console.log('Phase 74 passed: favorite cancellation requires online authoritative reconciliation and preserves all remaining queued intents.');
