import { strict as assert } from 'node:assert';
import { readFileSync } from 'node:fs';
import { decideOutboxHeadAction } from '../src/storage/outbox-sync-policy.mjs';
const base = { id: 'head-1', operation: 'create-ad', state: 'pending', attempts: 0, nextAttemptAt: 0 };
assert.deepEqual(decideOutboxHeadAction(null, 100), { status: 'nothing-due' });
assert.deepEqual(decideOutboxHeadAction({ ...base, state: 'processing' }, 100), { status: 'already-processing', id: 'head-1' });
assert.deepEqual(decideOutboxHeadAction({ ...base, state: 'failed', attempts: 8 }, 100), { status: 'blocked-by-exhausted', id: 'head-1', operation: 'create-ad', attempts: 8 });
assert.deepEqual(decideOutboxHeadAction({ ...base, nextAttemptAt: 101 }, 100), { status: 'waiting-for-retry', id: 'head-1', nextAttemptAt: 101 });
assert.deepEqual(decideOutboxHeadAction({ ...base, operation: 'delete-ad' }, 100), { status: 'send-delete-ad', id: 'head-1' });
