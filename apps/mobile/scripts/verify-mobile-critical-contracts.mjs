#!/usr/bin/env node
import assert from 'node:assert/strict';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { resolve, join } from 'node:path';
const app = resolve(import.meta.dirname, '..');
const repo = resolve(app, '../..');
const read = (p) => readFileSync(join(repo, p), 'utf8');
assert.ok(existsSync(join(app, 'src/api/response-validation.ts')), 'runtime response validation helper exists');
const client = read('apps/mobile/src/api/client.ts');
assert.match(client, /responseSchema\?: ZodType<T>/, 'API client accepts endpoint schemas');
assert.match(client, /parseApiResponse\(responseSchema, payload\)/, 'successful JSON is validated before use');
assert.match(client, /async function readValidatedCache/, 'offline cache data has a validation boundary');
assert.match(client, /readValidatedCache<T>\(cacheKey, responseSchema\)/, 'both fallback paths validate cached critical responses');
assert.match(client, /استجابة الخادم لا تطابق مخطط البيانات المتوقع/, 'malformed 2xx responses fail closed');
const auth = read('apps/mobile/src/features/auth/auth.api.ts');
assert.match(auth, /authEnvelopeResponseSchema/, 'login/register responses are schema-validated');
assert.match(auth, /refreshEnvelopeResponseSchema/, 'refresh response is schema-validated');
const ads = read('apps/mobile/src/features/ads/manage-ads.api.ts');
assert.ok((ads.match(/criticalAdEnvelopeResponseSchema/g) ?? []).length >= 3, 'ad create/update responses use runtime schema');
const orders = read('apps/mobile/src/features/commerce/orders.api.ts');
assert.match(orders, /criticalOrderEnvelopeResponseSchema/, 'order detail/mutation schema exists');
assert.match(orders, /criticalOrderListEnvelopeResponseSchema/, 'order list schema exists');
const database = read('apps/mobile/src/storage/encrypted-database.ts');
assert.match(database, /assertLegacyDataPreserved/, 'SQLCipher migration checks legacy row counts before deletion');
const outbox = read('apps/mobile/src/storage/outbox-manager.ts');
assert.match(outbox, /failedQueues/, 'outbox snapshot exposes queue read failures');
assert.match(outbox, /if \(!snapshot\.isComplete\)/, 'outbox counts fail closed for incomplete snapshots');
assert.match(outbox, /listPendingMarketplaceRequests/, 'request-create queue is part of the unified outbox snapshot');
assert.match(outbox, /listPendingRequestOffers/, 'request-offer queue is part of the unified outbox snapshot');
const policyFacade = read('apps/mobile/src/storage/outbox-sync-policy.ts');
assert.match(policyFacade, /from '\.\/outbox-sync-policy\.mjs'/, 'TypeScript outbox policy delegates to the canonical executable module');
const transportFacade = read('apps/mobile/src/storage/outbox-transport-contract.ts');
assert.match(transportFacade, /from '\.\/outbox-transport-contract\.mjs'/, 'TypeScript transport contract delegates to the canonical executable module');
assert.ok(existsSync(join(app, 'src/storage/__tests__/draft-operation-queue.test.mjs')), 'draft queue has Node tests against the canonical module');
assert.ok(!existsSync(join(app, 'src/storage/draft-operation-queue.ts')), 'no unused duplicate draft queue implementation remains');
assert.equal((outbox.match(/export async function countPendingChat\(/g) ?? []).length, 1, 'outbox manager has one fail-closed countPendingChat implementation');
assert.ok(existsSync(join(app, 'scripts/legacy-verifications/manifest.json')), 'legacy failed verifications are catalogued');
const rootMarkdown = readdirSync(app).filter((f) => f.endsWith('.md') && f !== 'README.md');
assert.deepEqual(rootMarkdown, [], 'apps/mobile root only contains README.md');
const errorReporting = read('apps/mobile/src/lib/error-reporting.ts');
assert.doesNotMatch(errorReporting, /require\(['"]@sentry\/react-native['"]\)/, 'missing Sentry SDK cannot break Metro module resolution');
assert.match(errorReporting, /using local logging only/, 'Sentry remains explicitly inactive without native adapter');
const eslintConfig = read('apps/mobile/.eslintrc.cjs');
assert.match(eslintConfig, /@typescript-eslint\/no-explicit-any/, 'mobile ESLint bans explicit any');
assert.match(eslintConfig, /Use a token from @\/theme\/tokens/, 'mobile ESLint bans raw hex colors');
const workflow = read('.github/workflows/release-mobile-production.yml');
assert.match(workflow, /:app:verifyProductionSigning/, 'production release workflow requires signing guard');
assert.match(workflow, /jarsigner -verify/, 'production bundle signature is verified');
console.log('PASS mobile critical contracts (API schemas, SQLCipher integrity, outbox fail-closed, docs, production signing)');
