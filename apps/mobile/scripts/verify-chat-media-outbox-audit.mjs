import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
const root = resolve(import.meta.dirname, '..');
const read = (path) => readFileSync(resolve(root, path), 'utf8');
const screen = read('app/messages/[id].tsx');
const api = read('src/features/messaging/messaging.api.ts');
const queue = read('src/storage/chat-media-outbox.ts');
const sync = read('src/features/messaging/chat-media-outbox-sync.ts');
const pkg = JSON.parse(read('package.json'));
const app = JSON.parse(read('app.json'));
assert.match(screen, /DocumentPicker\.getDocumentAsync/);
assert.match(screen, /AudioModule\.requestRecordingPermissionsAsync/);
assert.match(screen, /audioRecorder\.record\(\{ forDuration: 60 \}\)/);
assert.match(screen, /queueAndTryMedia\('image'/);
assert.match(screen, /queueAndTryMedia\('file'/);
assert.match(screen, /queueAndTryMedia\('audio'/);
assert.match(screen, /flushMediaOutbox/);
assert.match(api, /messages\/\$\{endpoint\}/);
assert.match(api, /'X-Offline-Op-Id': stableOperationId/);
assert.match(api, /sendChatAudio/);
assert.match(api, /sendChatFile/);
assert.match(queue, /CREATE TABLE IF NOT EXISTS chat_media_outbox/);
assert.match(queue, /FileSystem\.copyAsync/);
assert.match(queue, /withExclusiveTransactionAsync/);
assert.match(queue, /next_attempt_at/);
assert.match(queue, /MIN\(5000 \* \(1 << MIN\(attempts, 10\)\), 3600000\)/);
assert.match(queue, /MAX_PENDING_MEDIA = 30/);
assert.match(queue, /MAX_MEDIA_BYTES = 15 \* 1024 \* 1024/);
assert.match(queue, /input.kind === 'image' \? 5 \* 1024 \* 1024 : input.kind === 'audio' \? 8 \* 1024 \* 1024/);
assert.match(sync, /snapshot.signal\?\.aborted/);
assert.match(sync, /acknowledgeChatMedia/);
assert.match(sync, /deferChatMedia/);
assert.match(sync, /item\.operationId/);
assert.equal(pkg.dependencies['expo-audio'], '~58.0.9');
assert.equal(pkg.dependencies['expo-document-picker'], '~58.0.4');
assert.ok(app.expo.plugins.some((plugin) => Array.isArray(plugin) && plugin[0] === 'expo-audio'));
console.log('Chat media outbox audit passed.');
