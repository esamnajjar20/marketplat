import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { decideOutboxHeadAction } from '../src/storage/outbox-sync-policy.mjs';
const root = new URL('../', import.meta.url);
const read = (p) => readFile(new URL(p, root), 'utf8');
const base = { id:'head-delete', operation:'delete-ad', resourceId:'ad_123', payloadJson:'{}', idempotencyKey:'offline-op:delete:ad_123:1', state:'pending', attempts:0, createdAt:1, lastError:null, nextAttemptAt:0, leaseOwner:null, leaseUntil:0 };
assert.deepEqual(decideOutboxHeadAction(base, 10), { status:'send-delete-ad', id:'head-delete' });
assert.deepEqual(decideOutboxHeadAction({...base, operation:'update-ad'}, 10), { status:'send-update-ad', id:'head-delete' });
assert.equal(decideOutboxHeadAction({...base, nextAttemptAt:99}, 10).status, 'waiting-for-retry');
const transport = await read('src/storage/outbox-transport.ts');
assert.match(transport, /sendOutboxDeleteAd/);
assert.match(transport, /method: 'DELETE'/);
assert.match(transport, /'X-Offline-Op-Id': item\.idempotencyKey/);
assert.match(transport, /item\.resourceId\?\.trim\(\)/);
const sync = await read('src/storage/outbox-sync.ts');
assert.match(sync, /await sendOutboxDeleteAd\(claimed, token, csrfToken\)/);
assert.match(sync, /acknowledgeMutation\(claimed\.id, leaseOwner\)/);
const screen = await read('app/my-ads.tsx');
assert.match(screen, /enqueueMutation\(/);
assert.match(screen, /operation: 'delete-ad'/);
assert.match(screen, /لم يُحذف الإعلان من الخادم بعد/);
const queue = await read('app/offline-queue.tsx');
assert.match(queue, /item\.operation === 'update-ad'/, 'Queue UI must only mark update operations unsupported');
assert.match(queue, /item\.operation === 'delete-ad'/, 'Exhausted delete operations can be retried at FIFO head');
const api = await read('../api/src/modules/ads/ads.service.ts').catch(() => '');
assert.ok(api.length === 0 || /ad\.status === 'DELETED'/.test(api), 'Phase 62 idempotent API delete implementation remains present when API path is in workspace');
console.log('Phase 63 passed: offline delete is durably queued, FIFO-replayed with stable operation ID, and acknowledged only after a successful DELETE envelope.');
