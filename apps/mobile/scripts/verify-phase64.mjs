import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { decideOutboxHeadAction } from '../src/storage/outbox-sync-policy.mjs';
const root = new URL('../', import.meta.url);
const read = (p) => readFile(new URL(p, root), 'utf8');
const base = { id:'update-head', operation:'update-ad', resourceId:'ad-123', payloadJson:JSON.stringify({title:'عنوان',description:'وصف',city:'نابلس',price:10,categoryId:null,isNegotiable:false}), idempotencyKey:'offline-update:1:abc', state:'pending', attempts:0, createdAt:1, lastError:null, nextAttemptAt:0, leaseOwner:null, leaseUntil:0 };
assert.deepEqual(decideOutboxHeadAction(base, 10), {status:'send-update-ad', id:'update-head'});
assert.equal(decideOutboxHeadAction({...base, operation:'update-ad', nextAttemptAt:100}, 10).status, 'waiting-for-retry');
const transport = await read('src/storage/outbox-transport.ts');
assert.match(transport, /sendOutboxUpdateAd/);
assert.match(transport, /method: 'PATCH'/);
assert.match(transport, /'X-Offline-Op-Id': item\.idempotencyKey/);
assert.match(transport, /allowed = new Set\(\['title', 'description', 'city', 'price', 'categoryId', 'isNegotiable', 'images'\]\)/);
const sync = await read('src/storage/outbox-sync.ts');
assert.match(sync, /await sendOutboxUpdateAd\(claimed, token, csrfToken\)/);
assert.match(sync, /strict FIFO/);
const editor = await read('app/ad-editor.tsx');
assert.match(editor, /operation: 'update-ad'/);
assert.match(editor, /images: draft\.images\.map/, 'Updates adding images must retain durable image references for replay');
assert.match(editor, /لم يُحدّث الإعلان على الخادم بعد/);
const queue = await read('app/offline-queue.tsx');
assert.match(queue, /يتضمن هذا التعديل صورًا محفوظة محليًا/);
console.log('Phase 64 passed: field-only ad edits are durably queued and FIFO-replayed; image-bearing edits retain durable image references for replay.');
