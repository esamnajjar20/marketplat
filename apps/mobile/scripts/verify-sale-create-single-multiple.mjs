import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const mobile = new URL('../app/sale-create.tsx', import.meta.url);
const apiRoot = new URL('../../../apps/api/src/modules/sales/', import.meta.url);
const screen = readFileSync(mobile, 'utf8');
const validation = readFileSync(new URL('sales.validation.ts', apiRoot), 'utf8');
const service = readFileSync(new URL('sales.service.ts', apiRoot), 'utf8');
const outbox = readFileSync(new URL('../src/storage/entity-create-outbox.ts', import.meta.url), 'utf8');
assert.match(screen, /value: 'single'/, 'single-sale mode is available');
assert.match(screen, /value: 'multiple'/, 'multi-item mode is available');
assert.match(screen, /manualItems:/, 'multi-item payload is sent to the backend');
assert.match(screen, /إضافة صنف/, 'users can add line items');
assert.match(screen, /إجمالي الفاتورة/, 'multi-item total is displayed');
assert.match(validation, /manualItems: z\.array/, 'backend validates manual line items');
assert.match(validation, /manualItemsTotal/, 'backend validates payment against multi-item total');
assert.match(service, /for \(const item of manualItems\)/, 'backend persists each manual sale item');
assert.match(service, /offlineOperationId: offlineOperationId \?\? null/, 'sale creation retains idempotency key');
assert.match(outbox, /بنود الفاتورة المتعددة غير صالحة/, 'offline queue validates multi-item payload');
console.log('Sale creation single/multiple checks passed.');
